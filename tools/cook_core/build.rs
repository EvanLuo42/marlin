//! Compiles the cook targets in: the `[cook]` table of every `platforms/<name>/platform.toml`
//! (console manifests too, where their repositories are cloned), as `$OUT_DIR/platforms.rs`.
//! Names are checked here; values are checked by the const lookups in `src/platform.rs`, so a
//! manifest naming an unknown codec or format fails the build.

use std::fmt::Write as _;
use std::path::Path;

use toml::de::{DeTable, DeValue};

fn main() {
    let platforms = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../platforms");
    println!("cargo:rerun-if-changed={}", platforms.display());
    println!("cargo:rerun-if-env-changed=CARGO_CFG_MARLIN_PLATFORM");

    let mut manifests = Vec::new();
    for entry in std::fs::read_dir(&platforms).expect("reading platforms/") {
        let manifest = entry.unwrap().path().join("platform.toml");
        if manifest.is_file() {
            println!("cargo:rerun-if-changed={}", manifest.display());
            let text = std::fs::read_to_string(&manifest).unwrap();
            let entry = parse(&text).unwrap_or_else(|e| panic!("{}: {e}", manifest.display()));
            manifests.push(entry);
        }
    }
    manifests.sort_by(|a, b| a.0.cmp(&b.0));

    let host = std::env::var("CARGO_CFG_MARLIN_PLATFORM").unwrap_or_else(|_| {
        panic!("no `marlin_platform` cfg: build through .cargo/config.toml or `cargo xtask`")
    });
    let mut out = String::from("// Generated by build.rs from platforms/*/platform.toml.\n");
    writeln!(out, "pub(crate) const HOST: &str = {host:?};").unwrap();
    out.push_str("pub(crate) static PLATFORMS: &[Platform] = &[\n");
    for (name, cook) in &manifests {
        let families: Vec<String> = cook
            .texture_compression
            .iter()
            .map(|f| format!("texture_family({f:?})"))
            .collect();
        writeln!(
            out,
            "    Platform {{ name: {name:?}, texture_compression: &[{}], \
             texture_layout: texture_layout({:?}), head_codec: codec({:?}), \
             bulk_codec: codec({:?}), shader_target: {:?} }},",
            families.join(", "),
            cook.texture_layout,
            cook.head_codec,
            cook.bulk_codec,
            cook.shader_target,
        )
        .unwrap();
    }
    out.push_str("];\n");
    let path = Path::new(&std::env::var("OUT_DIR").unwrap()).join("platforms.rs");
    std::fs::write(path, out).unwrap();
}

struct Cook {
    texture_compression: Vec<String>,
    texture_layout: String,
    head_codec: String,
    bulk_codec: String,
    shader_target: String,
}

fn string(value: &DeValue, key: &str) -> Result<String, String> {
    value
        .as_str()
        .map(str::to_owned)
        .ok_or_else(|| format!("`{key}` must be a string"))
}

/// The manifest's name and its `[cook]` table; unknown `[cook]` keys are errors.
fn parse(text: &str) -> Result<(String, Cook), String> {
    let table = DeTable::parse(text).map_err(|e| e.to_string())?;
    let table = table.get_ref();
    let name = string(table.get("name").ok_or("missing `name`")?.get_ref(), "name")?;
    let cook = table
        .get("cook")
        .ok_or("missing the `[cook]` table (see platforms/windows/platform.toml)")?
        .get_ref()
        .as_table()
        .ok_or("`cook` must be a table")?;
    let (mut families, mut layout, mut head, mut bulk, mut shader) = (None, None, None, None, None);
    for (key, value) in cook.iter() {
        let (key, value) = (key.get_ref().as_ref(), value.get_ref());
        match key {
            "texture-compression" => {
                let array = value
                    .as_array()
                    .ok_or("`texture-compression` must be an array of strings")?;
                families = Some(
                    array
                        .iter()
                        .map(|v| string(v.get_ref(), key))
                        .collect::<Result<Vec<_>, _>>()?,
                );
            }
            "texture-layout" => layout = Some(string(value, key)?),
            "head-codec" => head = Some(string(value, key)?),
            "bulk-codec" => bulk = Some(string(value, key)?),
            "shader-target" => shader = Some(string(value, key)?),
            other => return Err(format!("unknown field `cook.{other}`")),
        }
    }
    let missing = |key: &str| format!("missing `cook.{key}`");
    Ok((
        name,
        Cook {
            texture_compression: families.ok_or_else(|| missing("texture-compression"))?,
            texture_layout: layout.ok_or_else(|| missing("texture-layout"))?,
            head_codec: head.ok_or_else(|| missing("head-codec"))?,
            bulk_codec: bulk.ok_or_else(|| missing("bulk-codec"))?,
            shader_target: shader.ok_or_else(|| missing("shader-target"))?,
        },
    ))
}
