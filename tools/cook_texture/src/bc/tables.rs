const fn build_masks3() -> [[u16; 3]; 64] {
    let mut masks = [[0; 3]; 64];
    let mut p = 0;
    while p < 64 {
        let mut i = 0;
        while i < 16 {
            masks[p][PARTITIONS3[p][i] as usize] |= 1 << i;
            i += 1;
        }
        p += 1;
    }
    masks
}

const MASKS3: [[u16; 3]; 64] = build_masks3();

/// Texel bit masks of each subset.
pub(crate) fn masks(subsets: usize, partition: usize) -> [u16; 3] {
    match subsets {
        1 => [0xffff, 0, 0],
        2 => {
            let m = PARTITIONS2[partition];
            [!m, m, 0]
        }
        _ => MASKS3[partition],
    }
}

/// Subset of texel `texel` in partition `partition` of a `subsets`-subset mode.
pub(crate) fn subset(subsets: usize, partition: usize, texel: usize) -> usize {
    match subsets {
        1 => 0,
        2 => (PARTITIONS2[partition] >> texel) as usize & 1,
        _ => PARTITIONS3[partition][texel] as usize,
    }
}

/// Anchor texels, one per subset: their index's top bit is implicitly 0.
pub(crate) fn anchors(subsets: usize, partition: usize) -> [usize; 3] {
    match subsets {
        1 => [0, 0, 0],
        2 => [0, ANCHOR2[partition] as usize, 0],
        _ => {
            let [a, b] = ANCHOR3[partition];
            [0, a as usize, b as usize]
        }
    }
}

pub(crate) fn is_anchor(subsets: usize, partition: usize, texel: usize) -> bool {
    anchors(subsets, partition)[..subsets].contains(&texel)
}
